#!/usr/bin/env python3
"""Assemble, seal and validate the SUPABRAND synthetic knowledge world.

SYNTHETIC TEST DATA. Builds `manifest.yaml` from `records/*.yaml`, computes
value contracts and the manifest approval hash with the OBDS 4.2.0 reference
implementation, validates the manifest (Foundation + Knowledge Records
extension), validates and resolves every Task Profile against the request
contexts in `requests/*.yaml`, and writes `validation-result.json` and
`inventory.md`.

Usage:
  python3 tools/build.py --obds-repo /path/to/openbranddefinition/obds [--seal]

`--seal` rewrites `governance.approval.approvedContentHash` in approved Task
Profiles (hash of the profile document without the approval block, §14.3
canonical hash, same convention as the manifest `approval.contentHash`).
Without `--seal` a mismatching approved profile is reported as an error.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
AS_OF = "2026-10-21T12:00:00Z"
MANIFEST_ID = "urn:obds:brand:supabrand-synthetic-world"
BRAND_IDENTITY_SCHEMA = "https://openbranddefinition.org/value-schemas/1.0.0/brand-identity.schema.json"
RULE_SCHEMA = "https://openbranddefinition.org/value-schemas/3.0.0/rule.schema.json"


def locate_repo(arg: str | None) -> Path:
    for candidate in [arg, os.environ.get("OBDS_REPO"), ROOT.parent.parent / "obds", ROOT.parent / "obds"]:
        if candidate and (Path(candidate) / "reference/foundation/src/obds_ref").is_dir():
            return Path(candidate)
    sys.exit("OBDS repository not found; pass --obds-repo or set OBDS_REPO (openbranddefinition/obds, tag v4.2.0)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--obds-repo")
    parser.add_argument("--seal", action="store_true")
    args = parser.parse_args()
    repo = locate_repo(args.obds_repo)
    sys.path.insert(0, str(repo / "reference/foundation/src"))
    from jsonschema import Draft202012Validator
    from obds_ref.canonical import manifest_content_hash, sha256_id, value_shape_hash
    from obds_ref.compiler import validate_manifest
    from obds_ref.governed_io import ValidationFailure, load_data
    from obds_ref.knowledge_records import resolve_task_profile, validate_manifest_extension

    world = load_data(ROOT / "records" / "00-world.yaml")
    elements: list[dict] = []
    record_files = sorted(p for p in (ROOT / "records").glob("*.yaml") if p.name != "00-world.yaml")
    for path in record_files:
        doc = load_data(path)
        for element in doc["elements"]:
            element.setdefault("scope", {})
            element.setdefault("sourceRefs", [])
            element.setdefault("validity", {"from": None, "to": None})
            element.setdefault("annotations", [])
            elements.append(element)

    schema_hashes = {
        BRAND_IDENTITY_SCHEMA: sha256_id(load_data(repo / "value-schemas/1.0.0/brand-identity.schema.json")),
        RULE_SCHEMA: sha256_id(load_data(repo / "value-schemas/3.0.0/rule.schema.json")),
    }
    contracts: dict[str, dict] = {}
    for element in elements:
        needs_contract = element.get("state") == "defined" and (
            element.get("nature") == "fact" or element.get("family") == "rules")
        if not needs_contract:
            continue
        shape = value_shape_hash(element["value"])
        schema_ref = RULE_SCHEMA if element["family"] == "rules" else BRAND_IDENTITY_SCHEMA
        contract_id = f"urn:obds:value-contract:supabrand.{element['family']}.{element['kind']}.{shape[7:15]}"
        contracts.setdefault(contract_id, {
            "id": contract_id, "family": element["family"], "kind": element["kind"],
            "shapeHash": shape, "schemaRef": schema_ref, "schemaHash": schema_hashes[schema_ref],
            "validatorRef": None,
        })
        element["valueContractRef"] = contract_id

    manifest = {
        "id": MANIFEST_ID, "kind": "brand-manifest", "name": world["name"], "owner": world["owner"],
        "schemaVersion": "1.0.0", "version": world["version"], "status": "approved",
        "createdAt": world["createdAt"], "updatedAt": world["updatedAt"],
        "profiles": ["obds-foundation", "obds-knowledge-records"],
        "knowledgeVocabulary": world["knowledgeVocabulary"],
        "elements": elements, "valueContracts": list(contracts.values()),
        "approval": {"approvedBy": world["approvedBy"], "approvedAt": world["approvedAt"], "contentHash": ""},
    }
    manifest["approval"]["contentHash"] = manifest_content_hash(manifest)
    manifest_path = ROOT / "manifest.yaml"
    manifest_path.write_text(
        "# SYNTHETIC TEST DATA. Generated by tools/build.py; edit records/*.yaml instead.\n"
        + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    reloaded = load_data(manifest_path)

    result = {"asOf": AS_OF, "obdsRepoCommit": None, "manifest": {}, "taskProfiles": [], "resolutions": []}
    head = repo / ".git" / "HEAD"
    if head.exists():
        ref = head.read_text().strip()
        if ref.startswith("ref: "):
            ref_path = repo / ".git" / ref[5:]
            ref = ref_path.read_text().strip() if ref_path.exists() else ref
        result["obdsRepoCommit"] = ref
    foundation_errors = validate_manifest(reloaded, verify_hash=True)
    extension_errors = validate_manifest_extension(reloaded)
    result["manifest"] = {
        "id": MANIFEST_ID, "version": manifest["version"], "contentHash": manifest["approval"]["contentHash"],
        "elementCount": len(elements), "valueContractCount": len(contracts),
        "foundationErrors": foundation_errors, "knowledgeRecordsErrors": extension_errors,
    }
    ok = not foundation_errors and not extension_errors

    profile_schema = load_data(repo / "schemas/4.2.0/task-profile.schema.json")
    profiles = {}
    for path in sorted((ROOT / "task-profiles").glob("*.yaml")):
        doc = load_data(path)
        errors = [f"{'.'.join(map(str, e.absolute_path)) or '$'}: {e.message}"
                  for e in Draft202012Validator(profile_schema).iter_errors(doc)]
        entry = {"file": path.name, "id": doc.get("id"), "version": doc.get("version"),
                 "governanceStatus": doc.get("governance", {}).get("status"), "schemaErrors": errors,
                 "taskProfileHash": sha256_id(doc)}
        governance = doc.get("governance", {})
        if governance.get("status") == "approved":
            payload = copy.deepcopy(doc)
            payload["governance"].pop("approval", None)
            expected = sha256_id(payload)
            actual = governance.get("approval", {}).get("approvedContentHash")
            if actual != expected:
                if args.seal:
                    doc["governance"]["approval"]["approvedContentHash"] = expected
                    path.write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
                    doc = load_data(path)
                    entry["taskProfileHash"] = sha256_id(doc)
                    entry["sealed"] = True
                else:
                    entry["schemaErrors"].append(f"approvedContentHash mismatch: expected {expected}")
            entry["approvedContentHash"] = doc["governance"]["approval"]["approvedContentHash"]
        if entry["schemaErrors"]:
            ok = False
        result["taskProfiles"].append(entry)
        profiles[path.stem] = doc

    for path in sorted((ROOT / "requests").glob("*.yaml")):
        request = load_data(path)
        profile = profiles.get(request["profile"])
        entry = {"request": path.name, "profile": request["profile"], "scope": request["scope"],
                 "expectation": request.get("expectation")}
        if profile is None:
            entry["error"] = "unknown profile"
            ok = False
        elif profile.get("governance", {}).get("status") != "approved" and not request.get("draftOk"):
            entry["error"] = "profile is not approved; set draftOk: true to resolve it for authoring only"
            ok = False
        else:
            entry["profileStatus"] = profile.get("governance", {}).get("status")
            try:
                resolution = resolve_task_profile(profile, reloaded, as_of=request.get("asOf", AS_OF),
                                                  request_scope=request["scope"])
                entry["profileEcho"] = resolution["profile"]
                entry["requirements"] = resolution["requirements"]
                entry["blocked"] = any(r["required"] and not r["satisfied"] for r in resolution["requirements"])
                expected_block = request.get("expectBlocked")
                if expected_block is not None and expected_block != entry["blocked"]:
                    entry["error"] = f"expected blocked={expected_block}"
                    ok = False
            except ValidationFailure as exc:
                entry["error"] = [str(e) for e in exc.args[0]] if exc.args else str(exc)
                ok = False
        result["resolutions"].append(entry)

    result["ok"] = ok
    (ROOT / "validation-result.json").write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_inventory(elements, contracts, result, profiles)
    print(f"elements={len(elements)} contracts={len(contracts)} profiles={len(profiles)} "
          f"requests={len(result['resolutions'])} ok={ok}")
    for err in foundation_errors + extension_errors:
        print("  manifest:", err)
    for entry in result["taskProfiles"]:
        for err in entry["schemaErrors"]:
            print(f"  {entry['file']}: {err}")
    for entry in result["resolutions"]:
        if entry.get("error"):
            print(f"  {entry['request']}: {entry['error']}")
    return 0 if ok else 1


def write_inventory(elements, contracts, result, profiles):
    by_domain = Counter(e.get("domain", "(none)") for e in elements)
    by_authority = Counter(e.get("authority", "binding(legacy)") for e in elements)
    by_market = Counter()
    for e in elements:
        markets = e.get("scope", {}).get("markets")
        for m in (markets or ["(global)"]):
            by_market[m] += 1
    by_family = Counter(e["family"] for e in elements)
    by_state = Counter(e["state"] for e in elements)
    as_of = result["asOf"]
    lines = ["# Inventory (generated by tools/build.py)", "", "SYNTHETIC TEST DATA. Snapshot as of " + as_of + ".", ""]
    lines += [f"Elements: {len(elements)} · value contracts: {len(contracts)} · task profiles: {len(profiles)} · "
              f"manifest contentHash `{result['manifest']['contentHash']}`", ""]

    def table(title, counter, key="Key"):
        out = [f"## {title}", "", f"| {key} | Records |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))]
        return out + [""]

    lines += table("Records by domain", by_domain, "Domain")
    lines += table("Records by authority", by_authority, "Authority")
    lines += table("Records by market scope", by_market, "Market")
    lines += table("Records by family", by_family, "Family")
    lines += table("Records by state", by_state, "State")
    lines += ["## Validity", ""]
    expired = [e["id"] for e in elements if e.get("validity", {}).get("to") and e["validity"]["to"] <= as_of]
    future = [e["id"] for e in elements if e.get("validity", {}).get("from") and e["validity"]["from"] > as_of]
    lines += [f"- Expired at {as_of}: " + (", ".join(f"`{i}`" for i in expired) or "none")]
    lines += [f"- Not yet valid at {as_of}: " + (", ".join(f"`{i}`" for i in future) or "none"), ""]
    subjects = defaultdict(list)
    for e in elements:
        subjects[e.get("subject", e["id"])].append(e["id"])
    lines += ["## Shared subjects (precedence groups)", ""]
    lines += [f"- `{s}`: " + ", ".join(f"`{i}`" for i in ids) for s, ids in sorted(subjects.items()) if len(ids) > 1] + [""]
    lines += ["## Dependencies (dependsOn and claim evidenceRefs)", "", "| Record | Depends on |", "|---|---|"]
    for e in elements:
        deps = list(e.get("dependsOn", []))
        if isinstance(e.get("value"), dict):
            deps += [r for r in e["value"].get("evidenceRefs", []) if r not in deps]
        if deps:
            lines.append(f"| `{e['id']}` | " + ", ".join(f"`{d}`" for d in deps) + " |")
    lines += ["", "## relatedTo (navigation only)", "", "| Record | Related |", "|---|---|"]
    lines += [f"| `{e['id']}` | " + ", ".join(f"`{d}`" for d in e["relatedTo"]) + " |" for e in elements if e.get("relatedTo")]
    lines += ["", "## Caveats", "", "| Record | Authority | Caveats |", "|---|---|---|"]
    lines += [f"| `{e['id']}` | {e.get('authority')} | " + " / ".join(e["caveats"]).replace("|", "\\|") + " |"
              for e in elements if e.get("caveats")]
    lines += ["", "## Task Profiles", "", "| File | id | version | status | approvedContentHash | taskProfileHash |", "|---|---|---|---|---|---|"]
    for p in result["taskProfiles"]:
        lines.append(f"| {p['file']} | `{p['id']}` | {p['version']} | {p['governanceStatus']} | "
                     f"`{p.get('approvedContentHash', '')}` | `{p['taskProfileHash']}` |")
    lines += ["", "## Resolution runs", "", "| Request | Profile | Blocked | Required gaps |", "|---|---|---|---|"]
    for r in result["resolutions"]:
        gaps = [f"{q['id']}: {'; '.join(q['gaps'])}" for q in r.get("requirements", []) if q["required"] and not q["satisfied"]]
        lines.append(f"| {r['request']} | `{r['profile']}` | {r.get('blocked', r.get('error'))} | "
                     + (" <br> ".join(gaps).replace("|", "\\|") or "none") + " |")
    lines += ["", "## Validation", "", f"- Foundation errors: {len(result['manifest']['foundationErrors'])}",
              f"- Knowledge Records errors: {len(result['manifest']['knowledgeRecordsErrors'])}",
              f"- Overall: {'PASS' if result['ok'] else 'FAIL'} (details in validation-result.json)", ""]
    (ROOT / "inventory.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
